# Build-time step for DESIGN.md Section 11.1: renders the operator's manual
# (Markdown) to a self-contained HTML page, then raw-DEFLATE-compresses both
# forms for embedding. Nothing here runs on the device - only its output
# (the two .deflate blobs and the generated sizes header) does.

import argparse
import sys
import zlib
from pathlib import Path

import markdown

# RFC 1951 raw DEFLATE, no gzip/zlib wrapper: uzlib_inflate (DESIGN.md
# §11.1) decodes this directly, with no header-skipping code needed on
# either side. wbits=-15 is the largest (32 KiB) window, matching
# UZLIB_INFLATE_WINDOW_SIZE in components/uzlib_inflate/uzlib_inflate.c -
# a smaller window here would only shrink compression gains slightly, since
# nothing on the device depends on the window size matching exactly (a
# smaller compressor window is always decodable by a larger device window).
_WBITS = -15
_LEVEL = 9

_MANUAL_MD_LINK_HEAD = '<link rel="alternate" type="text/markdown" href="/manual.md">'
_MANUAL_MD_LINK_BODY = '<p><a href="/manual.md">Raw Markdown version of this page</a></p>'

# Minimal standalone page around the HTML fragment python-markdown produces
# (it only renders the fragment, unlike pandoc's --standalone - this
# replaces that). Deliberately no CSS framework/font import: self-contained
# and small, consistent with this endpoint's whole point (DESIGN.md §11.1).
_HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
{head_link}
<style>
body {{ font-family: sans-serif; max-width: 40em; margin: 2em auto; padding: 0 1em; }}
code, pre {{ background: #f0f0f0; padding: 0.2em 0.4em; }}
pre code {{ display: block; padding: 0.6em; overflow-x: auto; }}
table {{ border-collapse: collapse; }}
th, td {{ border: 1px solid #ccc; padding: 0.3em 0.6em; }}
</style>
</head>
<body>
{body_link}
{content}
</body>
</html>
"""


def render_html(manual_md_path, title):
    source = manual_md_path.read_text(encoding="utf-8")
    # "tables": GFM-style tables (docs/manual.md's API reference table).
    # "fenced_code": ```-delimited code blocks (every example script in
    # docs/manual.md) - not part of python-markdown's core rendering,
    # unlike CommonMark, where it is.
    content = markdown.markdown(source, extensions=["tables", "fenced_code"])
    html = _HTML_TEMPLATE.format(title=title, head_link=_MANUAL_MD_LINK_HEAD, body_link=_MANUAL_MD_LINK_BODY,
                                  content=content)
    return html.encode("utf-8")


def deflate(data):
    co = zlib.compressobj(_LEVEL, zlib.DEFLATED, _WBITS)
    return co.compress(data) + co.flush()


def c_identifier(name):
    # Mirrors ESP-IDF's data_file_embed_asm.cmake: EMBED_FILES derives its
    # linker symbol names from CMake's string(MAKE_C_IDENTIFIER <basename>)
    # - dots (and anything else non-alphanumeric) become underscores.
    return "".join(c if c.isalnum() else "_" for c in name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manual", required=True, type=Path, help="path to docs/manual.md")
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--title", default="ESP32-S3 Telemetry Bridge - Operator's Manual")
    args = parser.parse_args()

    args.out_dir.mkdir(parents=True, exist_ok=True)

    manual_md = args.manual.read_bytes()
    manual_html = render_html(args.manual, args.title)

    assets = {
        "manual.md": manual_md,
        "manual.html": manual_html,
    }

    header_lines = [
        "// Generated by components/self_doc/gen_assets.py - do not edit.",
        "#pragma once",
        "",
    ]
    for filename, original in assets.items():
        compressed = deflate(original)
        (args.out_dir / f"{filename}.deflate").write_bytes(compressed)
        macro = f"SELF_DOC_{c_identifier(filename).upper()}_ORIGINAL_SIZE"
        header_lines.append(f"#define {macro} {len(original)}u")

    (args.out_dir / "self_doc_sizes.h").write_text("\n".join(header_lines) + "\n")

    for filename, original in assets.items():
        compressed_len = (args.out_dir / f"{filename}.deflate").stat().st_size
        print(f"self_doc: {filename}: {len(original)} -> {compressed_len} bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
